"""
Zawadi Daily Sales Reporter - Scheduler Setup Utility
=====================================================
Automated cross-platform scheduling tool for Windows Task Scheduler and Linux/macOS Cron.
Turns a manual Python script into a hands-free 6:00 PM daily product.

Usage:
  python setup_scheduler.py --install       # Register daily 6:00 PM schedule
  python setup_scheduler.py --status        # Check schedule status and next run time
  python setup_scheduler.py --run-now       # Trigger execution via scheduler engine
  python setup_scheduler.py --uninstall     # Remove scheduled task
  python setup_scheduler.py --time 18:00    # Specify custom schedule time (24h)
"""

from __future__ import annotations

import argparse
import os
import platform
import subprocess
import sys
from pathlib import Path

BASE_DIR = Path(__file__).resolve().parent
SCRIPT_PATH = BASE_DIR / "sales_reporter.py"
BAT_RUNNER_PATH = BASE_DIR / "run_automation.bat"
DEFAULT_TASK_NAME = "ZawadiDailySalesReporter"
DEFAULT_SCHEDULE_TIME = "18:00"  # 6:00 PM EAT


def generate_windows_batch_runner() -> Path:
    """
    Creates a dedicated batch launcher that pins working directory
    and runs the active Python interpreter.
    """
    python_exe = sys.executable
    content = f"""@echo off
REM ===================================================================
REM Zawadi Daily Sales Reporter - Automated Background Task Runner
REM Auto-generated by setup_scheduler.py
REM ===================================================================
cd /d "{BASE_DIR}"
"{python_exe}" "{SCRIPT_PATH}" >> "{BASE_DIR / 'automation.log'}" 2>&1
"""
    BAT_RUNNER_PATH.write_text(content, encoding="utf-8")
    return BAT_RUNNER_PATH


# -----------------------------------------------------------------------------
# Windows Task Scheduler Manager
# -----------------------------------------------------------------------------
def install_windows_task(task_name: str, time_str: str) -> bool:
    """Registers a daily task in Windows Task Scheduler using schtasks and PowerShell."""
    bat_file = generate_windows_batch_runner()

    cmd = [
        "schtasks",
        "/create",
        "/tn", task_name,
        "/tr", f'cmd.exe /c "{bat_file}"',
        "/sc", "daily",
        "/st", time_str,
        "/f",
    ]

    print(f"[*] Registering Windows Task Scheduler job: '{task_name}'...")
    print(f"[*] Schedule: Daily at {time_str} (Local Time)")
    print(f"[*] Target batch launcher: {bat_file}")

    result = subprocess.run(cmd, capture_output=True, text=True)
    if result.returncode != 0:
        print(f"[-] FAILED to create task: {result.stderr.strip() or result.stdout.strip()}")
        return False

    # Adjust task settings so it runs on laptops even when on battery power
    try:
        ps_script = (
            f'$task = Get-ScheduledTask -TaskName "{task_name}"; '
            f'$task.Settings.DisallowStartIfOnBatteries = $false; '
            f'$task.Settings.StopIfGoingOnBatteries = $false; '
            f'$task.Settings.StartWhenAvailable = $true; '
            f'Set-ScheduledTask -InputObject $task | Out-Null'
        )
        subprocess.run(["powershell", "-NoProfile", "-Command", ps_script], capture_output=True, text=True)
        print("[+] Configured battery resilience: task runs on both AC and battery power.")
    except Exception as exc:
        print(f"[!] Warning: Could not adjust battery power settings: {exc}")

    print(f"[+] SUCCESS: Task '{task_name}' scheduled daily for {time_str}.")
    return True


def uninstall_windows_task(task_name: str) -> bool:
    """Deletes the scheduled task from Windows Task Scheduler."""
    cmd = ["schtasks", "/delete", "/tn", task_name, "/f"]
    print(f"[*] Removing Windows Task Scheduler job: '{task_name}'...")
    result = subprocess.run(cmd, capture_output=True, text=True)
    if result.returncode == 0:
        print(f"[+] SUCCESS: Task '{task_name}' successfully deleted.")
        return True
    else:
        print(f"[-] Could not delete task: {result.stderr.strip() or result.stdout.strip()}")
        return False


def status_windows_task(task_name: str) -> bool:
    """Queries task details from Windows Task Scheduler."""
    cmd = ["schtasks", "/query", "/tn", task_name, "/v", "/fo", "LIST"]
    result = subprocess.run(cmd, capture_output=True, text=True)
    if result.returncode != 0:
        print(f"[-] Task '{task_name}' is NOT currently registered in Task Scheduler.")
        return False

    print("\n" + "=" * 65)
    print(f" Windows Task Scheduler Status: {task_name}")
    print("=" * 65)

    key_fields = {
        "TaskName": "Task Name",
        "Next Run Time": "Next Run Time",
        "Status": "Status",
        "Last Run Time": "Last Run Time",
        "Last Result": "Last Exit Code (0 = Success)",
        "Task To Run": "Command",
        "Schedule Type": "Frequency",
        "Start Time": "Scheduled Time",
    }

    for line in result.stdout.splitlines():
        if ":" in line:
            key, _, val = line.partition(":")
            clean_key = key.strip()
            if clean_key in key_fields:
                print(f"  * {key_fields[clean_key]:<28}: {val.strip()}")

    print("=" * 65)
    return True


def run_now_windows_task(task_name: str) -> bool:
    """Manually triggers the registered task via Task Scheduler."""
    print(f"[*] Triggering Task Scheduler job '{task_name}' now...")
    ps_cmd = ["powershell", "-NoProfile", "-Command", f'Start-ScheduledTask -TaskName "{task_name}"']
    result = subprocess.run(ps_cmd, capture_output=True, text=True)
    if result.returncode == 0:
        print(f"[+] Task '{task_name}' was triggered successfully via Task Scheduler engine.")
        return True
    else:
        fallback = subprocess.run(["schtasks", "/run", "/tn", task_name], capture_output=True, text=True)
        if fallback.returncode == 0:
            print(f"[+] Task '{task_name}' was triggered successfully.")
            return True
        else:
            print(f"[-] Failed to trigger task: {fallback.stderr.strip() or fallback.stdout.strip()}")
            return False


# -----------------------------------------------------------------------------
# Linux / macOS Cron Manager
# -----------------------------------------------------------------------------
def get_cron_entry(time_str: str) -> str:
    """Generates the crontab line for 6pm execution."""
    hh, mm = time_str.split(":")
    python_exe = sys.executable
    return f"{int(mm)} {int(hh)} * * * cd \"{BASE_DIR}\" && \"{python_exe}\" \"{SCRIPT_PATH}\" >> \"{BASE_DIR / 'automation.log'}\" 2>&1 # {DEFAULT_TASK_NAME}"


def install_unix_cron(time_str: str) -> bool:
    """Registers crontab entry on Linux or macOS."""
    print(f"[*] Configuring crontab for daily {time_str}...")
    read_cmd = ["crontab", "-l"]
    existing = subprocess.run(read_cmd, capture_output=True, text=True)
    lines = existing.stdout.splitlines() if existing.returncode == 0 else []

    filtered = [l for l in lines if DEFAULT_TASK_NAME not in l and l.strip()]
    new_entry = get_cron_entry(time_str)
    filtered.append(new_entry)
    new_crontab = "\n".join(filtered) + "\n"

    write_cmd = ["crontab", "-"]
    res = subprocess.run(write_cmd, input=new_crontab, text=True, capture_output=True)
    if res.returncode == 0:
        print(f"[+] SUCCESS: Added daily cron job:\n    {new_entry}")
        return True
    else:
        print(f"[-] FAILED to update crontab: {res.stderr.strip()}")
        return False


def uninstall_unix_cron() -> bool:
    """Removes crontab entry on Linux or macOS."""
    print("[*] Removing crontab entry...")
    read_cmd = ["crontab", "-l"]
    existing = subprocess.run(read_cmd, capture_output=True, text=True)
    if existing.returncode != 0:
        print("[!] No crontab found.")
        return True
    lines = [l for l in existing.stdout.splitlines() if DEFAULT_TASK_NAME not in l and l.strip()]
    new_crontab = "\n".join(lines) + "\n" if lines else ""

    if new_crontab:
        res = subprocess.run(["crontab", "-"], input=new_crontab, text=True, capture_output=True)
    else:
        res = subprocess.run(["crontab", "-r"], capture_output=True, text=True)

    if res.returncode == 0:
        print("[+] SUCCESS: Removed daily cron job.")
        return True
    else:
        print(f"[-] Failed to update crontab: {res.stderr.strip()}")
        return False


def status_unix_cron() -> bool:
    """Inspects crontab entries on Linux or macOS."""
    res = subprocess.run(["crontab", "-l"], capture_output=True, text=True)
    if res.returncode != 0:
        print("[-] No crontab entries configured.")
        return False
    matched = [l for l in res.stdout.splitlines() if DEFAULT_TASK_NAME in l]
    if matched:
        print("\n" + "=" * 65)
        print(" Active Cron Schedule")
        print("=" * 65)
        for m in matched:
            print(f"  {m}")
        print("=" * 65)
        return True
    else:
        print(f"[-] No scheduled job matching '{DEFAULT_TASK_NAME}' found in crontab.")
        return False


# -----------------------------------------------------------------------------
# Main CLI Driver
# -----------------------------------------------------------------------------
def main():
    parser = argparse.ArgumentParser(
        description="Daily Retail Sales Reporter - Task Scheduler / Cron Installer"
    )
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument(
        "--install",
        action="store_true",
        help="Install daily scheduled job (defaults to 18:00 / 6:00 PM).",
    )
    group.add_argument(
        "--uninstall",
        action="store_true",
        help="Remove daily scheduled job.",
    )
    group.add_argument(
        "--status",
        action="store_true",
        help="Check current status of the scheduled job.",
    )
    group.add_argument(
        "--run-now",
        action="store_true",
        help="Trigger the scheduled task immediately through the scheduler engine.",
    )

    parser.add_argument(
        "--time",
        type=str,
        default=DEFAULT_SCHEDULE_TIME,
        help=f"Schedule time in 24h HH:MM format (default: {DEFAULT_SCHEDULE_TIME}).",
    )
    parser.add_argument(
        "--task-name",
        type=str,
        default=DEFAULT_TASK_NAME,
        help=f"Scheduled task name (default: {DEFAULT_TASK_NAME}).",
    )

    args = parser.parse_args()
    is_windows = platform.system() == "Windows"

    if args.install:
        if is_windows:
            success = install_windows_task(args.task_name, args.time)
        else:
            success = install_unix_cron(args.time)
        sys.exit(0 if success else 1)

    elif args.uninstall:
        if is_windows:
            success = uninstall_windows_task(args.task_name)
        else:
            success = uninstall_unix_cron()
        sys.exit(0 if success else 1)

    elif args.status:
        if is_windows:
            success = status_windows_task(args.task_name)
        else:
            success = status_unix_cron()
        sys.exit(0 if success else 1)

    elif args.run_now:
        if is_windows:
            success = run_now_windows_task(args.task_name)
        else:
            print("[*] Running script directly for Unix/Mac...")
            res = subprocess.run([sys.executable, str(SCRIPT_PATH)])
            success = res.returncode == 0
        sys.exit(0 if success else 1)


if __name__ == "__main__":
    main()
